_DEFAULT_ICON: str = "sparkle"
_WORD: re.Pattern[str] = re.compile(r"[a-z0-9][a-z0-9+#-]*")


def skill_icon(declared: str | None, texts: Iterable[str]) -> str:
    """The icon of a skill: ``declared`` when it is one of the interface's, else the first of ``_BY_WORDS`` whose words
    meet those of ``texts`` (the name, then the description), else the spark."""
    if declared is not None and declared in ICON_NAMES:
        return declared
    for text in texts:
        words: set[str] = set(_WORD.findall(text.lower()))
        words |= {part for word in words for part in word.split("-")}
        for about, icon in _BY_WORDS:
            if words & about:
                return icon
    return _DEFAULT_ICON
